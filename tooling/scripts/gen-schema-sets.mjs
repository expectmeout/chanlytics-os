#!/usr/bin/env node
/**
 * Every closed set the database enforces, generated from the database itself.
 *
 * Reads each single-column CHECK of the form `col = ANY (ARRAY[...])` in the
 * public schema -- which is how Postgres stores `check (col in (...))` -- from
 * the LOCAL database that `supabase start` builds out of every migration, and
 * writes packages/contracts/src/schema-sets.generated.ts. Then
 * packages/contracts/src/schema-sets.ts holds every hand-kept list and type to
 * that file at compile time.
 *
 *   supabase start
 *   pnpm gen:schema-sets             write the file
 *   pnpm gen:schema-sets --check     exit 1 if the file is stale (CI)
 *
 * SUPABASE_CLI names the binary when `supabase` is not on PATH.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "packages/contracts/src/schema-sets.generated.ts");
const CLI = process.env.SUPABASE_CLI || "supabase";
const CHECK = process.argv.includes("--check");

// Values are quoted SQL literals inside the constraint's definition; a doubled
// quote is a quote. `conislocal` leaves out what a partition inherits, so each
// column is listed once, on the table that declares it.
const SQL = `
select t.relname::text as tbl,
       a.attname::text as col,
       to_jsonb(array(
         select m[1] from regexp_matches(pg_get_constraintdef(c.oid), '''((?:[^'']|'''')*)''::text', 'g') as m
       )) as vals
  from pg_constraint c
  join pg_class t on t.oid = c.conrelid
  join pg_attribute a on a.attrelid = c.conrelid and a.attnum = c.conkey[1]
 where c.contype = 'c'
   and c.connamespace = 'public'::regnamespace
   and c.conislocal
   and array_length(c.conkey, 1) = 1
   and pg_get_constraintdef(c.oid) like '%= ANY (ARRAY[%'
 order by 1, 2`;

function readSets() {
  // The npm-distributed CLI is a JavaScript launcher; run that one with this Node.
  const [cmd, pre] = CLI.endsWith(".js") ? [process.execPath, [CLI]] : [CLI, []];
  let out;
  try {
    out = execFileSync(cmd, [...pre, "db", "query", SQL, "-o", "json"], { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  } catch (e) {
    console.error(`gen-schema-sets: could not query the local database with "${CLI}". Is \`supabase start\` running? ${e instanceof Error ? e.message : e}`);
    process.exit(2);
  }
  const at = [out.indexOf("{"), out.indexOf("[")].filter((i) => i >= 0).sort((x, y) => x - y)[0];
  const parsed = JSON.parse(out.slice(at));
  const rows = Array.isArray(parsed) ? parsed : parsed.rows;
  const sets = new Map();
  for (const r of rows) {
    const key = `${r.tbl}.${r.col}`;
    if (sets.has(key)) {
      console.error(`gen-schema-sets: ${key} has two value-set CHECKs; one column, one set`);
      process.exit(2);
    }
    const vals = (typeof r.vals === "string" ? JSON.parse(r.vals) : r.vals).map((v) => v.replace(/''/g, "'"));
    sets.set(key, vals);
  }
  // A database this small is not the one the migrations build: refuse rather
  // than write a file that would make every assertion fail for the wrong reason.
  if (sets.size < 20) {
    console.error(`gen-schema-sets: found only ${sets.size} sets -- is this the database \`supabase start\` built from supabase/migrations?`);
    process.exit(2);
  }
  return sets;
}

function render(sets) {
  const entry = (key, vals) => {
    const quoted = vals.map((v) => JSON.stringify(v));
    const one = `  ${JSON.stringify(key)}: [${quoted.join(", ")}],`;
    if (one.length <= 110) return one;
    const rows = [];
    let row = "";
    for (const q of quoted) {
      if (row && (row + ", " + q).length > 100) { rows.push(row + ","); row = q; } else { row = row ? `${row}, ${q}` : q; }
    }
    rows.push(row + ",");
    return `  ${JSON.stringify(key)}: [\n${rows.map((r) => `    ${r}`).join("\n")}\n  ],`;
  };
  return [
    "/**",
    " * GENERATED by tooling/scripts/gen-schema-sets.mjs from the database's own CHECK",
    " * constraints: every closed set Postgres enforces, one entry per column, values",
    " * in the constraint's order. Do not edit. Change the migration, then run",
    " * `pnpm gen:schema-sets` with `supabase start` running. The Database workflow",
    " * regenerates this on every pull request and fails when it is stale, and",
    " * schema-sets.ts holds every hand-kept list to it at compile time.",
    " */",
    "export const SCHEMA_SETS = {",
    ...[...sets].map(([k, v]) => entry(k, v)),
    "} as const;",
    "",
  ].join("\n");
}

const next = render(readSets());
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
if (CHECK) {
  if (current === next) {
    console.log(`schema-sets.generated.ts is current (${next.split("\n").filter((l) => /^ {2}"/.test(l)).length} sets).`);
    process.exit(0);
  }
  const keys = (s) => new Set([...s.matchAll(/^ {2}"([^"]+)"/gm)].map((m) => m[1]));
  const was = keys(current);
  const now = keys(next);
  const added = [...now].filter((k) => !was.has(k));
  const gone = [...was].filter((k) => !now.has(k));
  console.error("schema-sets.generated.ts is stale: a migration changed a CHECK and the file was not regenerated.");
  if (added.length) console.error(`  new: ${added.join(", ")}`);
  if (gone.length) console.error(`  gone: ${gone.join(", ")}`);
  if (!added.length && !gone.length) console.error("  a set's values changed");
  console.error("Run `pnpm gen:schema-sets` with `supabase start` running, and commit the result.");
  process.exit(1);
}
fs.writeFileSync(OUT, next);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
