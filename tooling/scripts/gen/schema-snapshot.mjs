#!/usr/bin/env node
/**
 * The schema as the migrations leave it, in one file.
 *
 * A function redefined across migrations lives in whichever file came last, so
 * learning what one does today meant finding the newest of up to sixteen
 * copies. supabase/schema.sql is that answer written down: `pg_dump
 * --schema-only` of the `public` schema (the one schema the migrations own) on
 * the LOCAL stack, the database `supabase start` builds out of every migration.
 * pg_dump runs inside the stack's own database container, so it is the
 * server's version and no port has to reach it from this machine. Nothing
 * applies the file: the migrations are the source, and supabase/config.toml's
 * `schema_paths` stays empty.
 *
 *   supabase start
 *   corepack pnpm gen:schema-snapshot                          write supabase/schema.sql
 *   node tooling/scripts/gen/schema-snapshot.mjs --check       exit 1 if it is stale (schema-snapshot.db.test.mjs)
 *
 * What is environment rather than schema is left out, so two replays on two
 * machines on two days write the same bytes:
 *  - the monthly partitions of `events` (events_yYYYYmMM), with their indexes,
 *    constraints and grants: 00002 creates them around the day the migrations
 *    run, so a replay in October has tables a replay in August does not;
 *  - owners, and the default privileges of supabase_admin, the platform's own
 *    role: the image sets those, no migration does;
 *  - pg_dump's version lines and its `\restrict` key, which is new every run;
 *  - carriage returns: a Windows checkout replays its function bodies with CR LF.
 *
 * Exit codes: 0 current (or written), 1 stale, 2 the dump could not be taken --
 * a check that cannot run must not pass. SUPABASE_WORKDIR names the project
 * directory whose supabase/config.toml names the stack, as it does for the CLI;
 * its `project_id` names the container.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const OUT = "supabase/schema.sql";
export const FIX = "supabase start && corepack pnpm gen:schema-snapshot";

/** A month's partition of `events`, by the name 00002 and ensure_events_partition give it. */
const PARTITION = /\bevents_y\d{4}m\d{2}/;
/** The same months as pg_dump reads a pattern: `?` is one character. */
const PARTITION_PATTERN = "public.events_y????m??";

/** A default privilege the platform's own role holds: the image's, not a migration's. */
const PLATFORM_DEFAULT = /^ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin /;
/** The line after pg_dump's last entry. */
const TRAILER = "\n--\n-- PostgreSQL database dump complete\n--";

const HEADER = [
  "--",
  "-- GENERATED by tooling/scripts/gen/schema-snapshot.mjs: the public schema as every migration",
  "-- in supabase/migrations leaves it, dumped from a replay. Do not edit, and nothing applies it:",
  "-- change a migration, then run `corepack pnpm gen:schema-snapshot` with `supabase start` running.",
  "-- The monthly partitions of events (events_yYYYYmMM) are left out: which exist is the calendar's.",
  "--",
  "",
  "",
];

/**
 * pg_dump's output as the snapshot keeps it: LF endings; from its first SET to
 * its last entry, so the version lines and the `\restrict` key above and below
 * are gone; no month's partition of `events`; none of the platform's default
 * privileges; and this script's header on top. Entries are kept byte for byte,
 * so a function's body is what pg_proc holds.
 */
export function normalise(dump) {
  const text = dump.replace(/\r\n/g, "\n");
  const start = text.search(/^SET /m);
  const end = text.lastIndexOf(TRAILER);
  if (start < 0 || end < start) throw new Error("not a pg_dump of a schema: no SET preamble, or no closing line");
  const entries = text.slice(start, end).split(/\n(?=--\n-- Name: )/);
  const kept = entries.filter((entry) => {
    const header = /^--\n-- Name: ([^\n]*)/.exec(entry)?.[1] ?? "";
    if (PARTITION.test(header)) return false;
    const statements = entry.split("\n").filter((l) => l && !l.startsWith("--"));
    return !(statements.length > 0 && statements.every((l) => PLATFORM_DEFAULT.test(l)));
  });
  return HEADER.join("\n") + kept.join("\n").replace(/\n+$/, "\n");
}

/* ---- Reading SQL: the migrations and the snapshot, by the same rules ---- */

const WORD = /[A-Za-z0-9_$]/;
const DOLLAR_TAG = /^\$([A-Za-z_][A-Za-z0-9_]*)?\$/;

/**
 * SQL as tokens, each with where it starts and ends in `sql`: a word, a quoted
 * name (`ident`), a string, a dollar-quoted string (`dollar`, its `value` what
 * pg_proc keeps of a body), or one character of punctuation. Comments and
 * blanks are not tokens; everything a token covers is kept as written.
 */
export function tokensOf(sql) {
  const out = [];
  const n = sql.length;
  let i = 0;
  while (i < n) {
    const c = sql[i];
    if (c === " " || c === "\t" || c === "\n" || c === "\r") {
      i++;
    } else if (c === "-" && sql[i + 1] === "-") {
      const e = sql.indexOf("\n", i);
      i = e < 0 ? n : e;
    } else if (c === "/" && sql[i + 1] === "*") {
      let depth = 1;
      i += 2;
      while (i < n && depth > 0) {
        if (sql.startsWith("/*", i)) (depth++, (i += 2));
        else if (sql.startsWith("*/", i)) (depth--, (i += 2));
        else i++;
      }
    } else if (c === "'") {
      // E'…' takes backslash escapes; every string takes '' for a quote.
      const escapes = /[Ee]/.test(sql[i - 1] ?? "") && !WORD.test(sql[i - 2] ?? "");
      let j = i + 1;
      while (j < n) {
        if (escapes && sql[j] === "\\") j += 2;
        else if (sql[j] === "'" && sql[j + 1] === "'") j += 2;
        else if (sql[j] === "'") break;
        else j++;
      }
      out.push({ type: "string", start: i, end: j + 1, value: sql.slice(i + 1, j).replace(/''/g, "'") });
      i = j + 1;
    } else if (c === '"') {
      let j = i + 1;
      while (j < n && !(sql[j] === '"' && sql[j + 1] !== '"')) j += sql[j] === '"' ? 2 : 1;
      out.push({ type: "ident", start: i, end: j + 1, value: sql.slice(i + 1, j).replace(/""/g, '"') });
      i = j + 1;
    } else if (c === "$" && !WORD.test(sql[i - 1] ?? "") && DOLLAR_TAG.test(sql.slice(i, i + 64))) {
      const tag = DOLLAR_TAG.exec(sql.slice(i, i + 64))[0];
      const close = sql.indexOf(tag, i + tag.length);
      const end = close < 0 ? n : close + tag.length;
      out.push({ type: "dollar", start: i, end, value: sql.slice(i + tag.length, close < 0 ? n : close) });
      i = end;
    } else if (WORD.test(c)) {
      let j = i + 1;
      while (j < n && WORD.test(sql[j])) j++;
      out.push({ type: "word", start: i, end: j, value: sql.slice(i, j) });
      i = j;
    } else {
      out.push({ type: "punct", start: i, end: i + 1, value: c });
      i++;
    }
  }
  return out;
}

/** The top-level statements of `sql`, each its tokens and its text from first token to last. */
export function statementsOf(sql) {
  const statements = [];
  let tokens = [];
  const close = () => {
    if (tokens.length > 0) {
      statements.push({ tokens, text: sql.slice(tokens[0].start, tokens[tokens.length - 1].end) });
    }
    tokens = [];
  };
  for (const t of tokensOf(sql)) {
    if (t.type === "punct" && t.value === ";") close();
    else tokens.push(t);
  }
  close();
  return statements;
}

/** The index of the `)` that closes the `(` at `open`, among tokens. */
export function closing(tokens, open) {
  let depth = 0;
  for (let i = open; i < tokens.length; i++) {
    if (tokens[i].type !== "punct") continue;
    if (tokens[i].value === "(") depth++;
    else if (tokens[i].value === ")" && --depth === 0) return i;
  }
  return -1;
}

/** Tokens cut at the commas outside any parentheses. */
export function splitTopLevel(tokens, sep = ",") {
  const parts = [[]];
  let depth = 0;
  for (const t of tokens) {
    if (t.type === "punct" && (t.value === "(" || t.value === "[")) depth++;
    if (t.type === "punct" && (t.value === ")" || t.value === "]")) depth--;
    if (depth === 0 && t.type === "punct" && t.value === sep) parts.push([]);
    else parts[parts.length - 1].push(t);
  }
  return parts.filter((p) => p.length > 0);
}

const is = (t, word) => t?.type === "word" && t.value.toLowerCase() === word;

/** A type's spellings that Postgres reads as one: the name pg_dump writes, for any alias a migration may use. */
const TYPE_NAMES = {
  int: "integer",
  int4: "integer",
  int2: "smallint",
  int8: "bigint",
  bool: "boolean",
  float8: "double precision",
  float: "double precision",
  float4: "real",
  varchar: "character varying",
  char: "character",
  bpchar: "character",
  decimal: "numeric",
  timestamptz: "timestamp with time zone",
  timestamp: "timestamp without time zone",
  timetz: "time with time zone",
  time: "time without time zone",
};

/** A parameter's type as its identity reads it: lower case, no modifier, no schema, one spelling per type. */
export function canonicalType(text) {
  const arrays = (text.match(/\[\s*\d*\s*\]/g) ?? []).length;
  const base = text
    .replace(/\[\s*\d*\s*\]/g, "")
    .replace(/\(\s*\d+(\s*,\s*\d+)?\s*\)/g, "")
    .replace(/"/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
    .replace(/^public\./, "")
    .replace(/^pg_catalog\./, "");
  return (TYPE_NAMES[base] ?? base) + "[]".repeat(arrays);
}

const MODES = new Set(["in", "out", "inout", "variadic"]);
/** Types spelled in more than one word; the first word alone would read as a parameter's name. */
const MULTI_WORD_TYPE =
  /^(double precision|character varying|bit varying|(timestamp|time)( ?\(\d+\))? with(out)? time zone)\b/i;

/**
 * One parameter of a signature: its mode and type (the name and default left
 * out), from a CREATE FUNCTION's list or a DROP FUNCTION's.
 */
function parameterOf(tokens, sql) {
  let ts = tokens;
  const cut = ts.findIndex((t, i) => i > 0 && (is(t, "default") || (t.type === "punct" && t.value === "=")));
  if (cut > 0) ts = ts.slice(0, cut);
  let mode = "in";
  if (ts.length > 1 && ts[0].type === "word" && MODES.has(ts[0].value.toLowerCase())) {
    mode = ts[0].value.toLowerCase();
    ts = ts.slice(1);
  }
  const text = (from) => sql.slice(ts[from].start, ts[ts.length - 1].end);
  // `p_at timestamptz` is a name and a type; `text[]`, `numeric(10,2)` and `public.kind` are a type alone.
  const named = ts.length > 1 && ts[1].type !== "punct" && !MULTI_WORD_TYPE.test(text(0));
  return { mode, type: canonicalType(text(named ? 1 : 0)) };
}

/** A function's identity: its name and the types of what it takes in, as Postgres tells two apart. */
function identityOf(name, paramTokens, sql) {
  const types = splitTopLevel(paramTokens)
    .map((p) => parameterOf(p, sql))
    .filter((p) => p.mode !== "out")
    .map((p) => p.type);
  return `${name}(${types.join(", ")})`;
}

/** `public.name`, `name` or `"name"`, at `at`: the name, and the index after it. */
export function qualifiedName(tokens, at) {
  let i = at;
  const part = (t) => (t?.type === "word" || t?.type === "ident" ? t.value : null);
  let name = part(tokens[i]);
  if (tokens[i + 1]?.type === "punct" && tokens[i + 1].value === ".") {
    if (name?.toLowerCase() !== "public") return { name: null, next: i };
    i += 2;
    name = part(tokens[i]);
  }
  return { name: name?.toLowerCase() ?? null, next: i + 1 };
}

/**
 * What a script does to functions, in order: each `create` with the function's
 * identity and body (what pg_proc keeps, or null for a body written as SQL
 * rather than a string), and each `drop` with the identity it names, or `name(*)`
 * when it names no parameters.
 */
export function functionChangesIn(sql) {
  return statementsOf(sql).flatMap(({ tokens }) => {
    if (is(tokens[0], "create")) return createdBy(tokens, sql);
    if (is(tokens[0], "drop") && (is(tokens[1], "function") || is(tokens[1], "procedure")))
      return droppedBy(tokens, sql);
    return [];
  });
}

/** `create [or replace] function public.name(…) … as $$body$$`, as a change, or none for any other CREATE. */
function createdBy(tokens, sql) {
  const at = is(tokens[1], "or") && is(tokens[2], "replace") ? 3 : 1;
  if (!is(tokens[at], "function") && !is(tokens[at], "procedure")) return [];
  const { name, next } = qualifiedName(tokens, at + 1);
  if (!name || tokens[next]?.value !== "(") return [];
  const end = closing(tokens, next);
  // The body is the string after AS: dollar-quoted as a rule, single-quoted now and then.
  const body = tokens.find(
    (t, k) => k > end && (t.type === "dollar" || (t.type === "string" && is(tokens[k - 1], "as"))),
  );
  return [
    { kind: "create", name, identity: identityOf(name, tokens.slice(next + 1, end), sql), body: body?.value ?? null },
  ];
}

/** `drop function [if exists] public.a(…), public.b(…) [cascade]`, one change per function it names. */
function droppedBy(tokens, sql) {
  const from = is(tokens[2], "if") && is(tokens[3], "exists") ? 4 : 2;
  const named = tokens.slice(from).filter((t) => !is(t, "cascade") && !is(t, "restrict"));
  return splitTopLevel(named).flatMap((one) => {
    const { name, next } = qualifiedName(one, 0);
    if (!name) return [];
    const params = one[next]?.value === "(" ? one.slice(next + 1, closing(one, next)) : null;
    return [{ kind: "drop", name, identity: params ? identityOf(name, params, sql) : `${name}(*)` }];
  });
}

/**
 * The stack's database container, as the CLI names it: `supabase_db_` and the
 * project_id of the config it was started from, made safe the way the CLI makes it.
 */
export function containerOf(configToml) {
  const id = /^\s*project_id\s*=\s*"([^"]*)"/m.exec(configToml)?.[1];
  if (!id) return null;
  return `supabase_db_${id.replace(/[^a-zA-Z0-9_.-]+/g, "_").slice(0, 40)}`;
}

/** Where the two files first part, by line, so a red run names the object rather than a byte offset. */
function firstDifference(committed, generated) {
  const a = committed.split("\n");
  const b = generated.split("\n");
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  let within = null;
  for (let j = Math.min(i, a.length - 1); j >= 0 && !within; j--) within = /^-- Name: ([^\n]*)/.exec(a[j])?.[1] ?? null;
  return { line: i + 1, within, committed: a[i] ?? null, generated: b[i] ?? null };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
  const WORKDIR = process.env.SUPABASE_WORKDIR || ROOT;
  const check = process.argv.includes("--check");
  const out = path.join(ROOT, OUT);

  const configPath = path.join(WORKDIR, "supabase", "config.toml");
  const container = fs.existsSync(configPath) ? containerOf(fs.readFileSync(configPath, "utf8")) : null;
  if (!container) {
    console.error(`schema-snapshot: no project_id in ${configPath}, so no stack to dump.`);
    process.exit(2);
  }
  let dump;
  try {
    dump = execFileSync(
      "docker",
      [
        "exec",
        container,
        "pg_dump",
        "--username=postgres",
        "--schema-only",
        "--schema=public",
        `--exclude-table=${PARTITION_PATTERN}`,
        "--no-owner",
      ],
      { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 256 * 1024 * 1024 },
    );
  } catch (e) {
    const why = (e && typeof e.stderr === "string" && e.stderr.trim()) || (e instanceof Error ? e.message : String(e));
    console.error(`schema-snapshot: could not dump ${container}. Is \`supabase start\` running? ${why}`);
    process.exit(2);
  }
  // A database with no tables in public is not the one the migrations build:
  // refuse rather than write, or pass, an empty schema.
  const tables = (dump.match(/^CREATE TABLE public\./gm) ?? []).length;
  if (tables < 20) {
    console.error(
      `schema-snapshot: ${container} has ${tables} tables in public -- is it the stack built from supabase/migrations?`,
    );
    process.exit(2);
  }
  const generated = normalise(dump);
  const lines = generated.split("\n").length - 1;
  if (!check) {
    fs.writeFileSync(out, generated);
    console.log(`wrote ${OUT} (${lines} lines, ${tables} tables) from ${container}`);
    process.exit(0);
  }
  const committed = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (committed === generated) {
    console.log(`${OUT} is current (${lines} lines, ${tables} tables), against ${container}.`);
    process.exit(0);
  }
  const d = firstDifference(committed, generated);
  console.error(`${OUT} is stale: the migrations build a schema the committed snapshot does not hold.`);
  console.error(`  first difference at line ${d.line}${d.within ? `, in ${d.within}` : ""}:`);
  console.error(`    committed  ${d.committed ?? "(end of file)"}`);
  console.error(`    generated  ${d.generated ?? "(end of file)"}`);
  console.error(`Run \`${FIX}\`, and commit the result.`);
  process.exit(1);
}
