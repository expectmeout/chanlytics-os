#!/usr/bin/env node
/**
 * The route registry the typed client reads: one key per handler, in the
 * form route-policy.json already uses ("GET conversations/[id]"), with the
 * method and path at runtime and the handler's type via `typeof import()`,
 * which TypeScript resolves and no bundler ever loads.
 *
 * Beside it, the same keys for contracts (`ROUTE_KEYS`, `ApiRouteKey`), which
 * depends on zod alone and may import nothing of the dashboard's: a contract
 * that names a route (the Ask cards' specs, ask-proposals.ts) names one of
 * these, and the dashboard's walk hands it to the typed client. What a route
 * takes and answers stays the dashboard's (client/api.ts `Input`, `Output`).
 * The precedent for a generated file in contracts is gen-schema-sets.mjs.
 *
 *   node tooling/scripts/gen-route-types.mjs          # write both
 *   node tooling/scripts/gen-route-types.mjs --check  # exit 1 when either is stale
 *
 * route-types.test.mjs regenerates both in memory on every run and refuses a
 * stale copy, so CI holds the files to the routes.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const OUT = "apps/dashboard/src/client/routes.generated.ts";
export const KEYS_OUT = "packages/contracts/src/route-keys.generated.ts";
const API = "apps/dashboard/app/api/v1";
const METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"];

export function generate(root) {
  const files = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name === "route.ts") files.push(p);
    }
  })(path.join(root, API));
  const entries = [];
  for (const f of files.sort()) {
    const rel = path
      .relative(path.join(root, API), f)
      .replace(/\\/g, "/")
      .replace(/\/route\.ts$/, "");
    const src = fs.readFileSync(f, "utf8");
    for (const m of METHODS) {
      if (!new RegExp(`^export const ${m} = `, "m").test(src)) continue;
      entries.push({ key: `${m} ${rel}`, method: m, path: `/api/v1/${rel}`, module: `../../app/api/v1/${rel}/route` });
    }
  }
  entries.sort((a, b) => (a.key < b.key ? -1 : 1));
  const lines = [
    "/* Generated by tooling/scripts/gen-route-types.mjs from apps/dashboard/app/api/v1 — do not edit. */",
    "",
    "/** Every handler under /api/v1, keyed the way route-policy.json keys it. */",
    "export const ROUTES = {",
    ...entries.map(
      (e) => `  ${JSON.stringify(e.key)}: { method: ${JSON.stringify(e.method)}, path: ${JSON.stringify(e.path)} },`,
    ),
    "} as const;",
    "",
    "/** The handler each key names, as a type: what it takes and answers rides on it (route.ts, Shape). */",
    "export type Routes = {",
    ...entries.map((e) => `  ${JSON.stringify(e.key)}: typeof import(${JSON.stringify(e.module)}).${e.method};`),
    "};",
    "",
  ];
  const keyLines = [
    "/* Generated by tooling/scripts/gen-route-types.mjs from apps/dashboard/app/api/v1 — do not edit. */",
    "",
    "/**",
    " * Every handler under /api/v1, keyed the way route-policy.json keys it: the dashboard's typed client's keys",
    " * (client/routes.generated.ts), for a contract that names a route. What each takes and answers is the dashboard's.",
    " */",
    "export const ROUTE_KEYS = [",
    ...entries.map((e) => `  ${JSON.stringify(e.key)},`),
    "] as const;",
    "",
    '/** A route by its key: "POST conversations/[id]/reply". */',
    "export type ApiRouteKey = (typeof ROUTE_KEYS)[number];",
    "",
  ];
  return { text: lines.join("\n"), keysText: keyLines.join("\n"), keys: entries.map((e) => e.key) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const { text, keysText } = generate(root);
  const outs = [
    [OUT, text],
    [KEYS_OUT, keysText],
  ];
  if (process.argv.includes("--check")) {
    const stale = outs.filter(([rel, want]) => {
      const file = path.join(root, rel);
      return !fs.existsSync(file) || fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== want;
    });
    console.log(
      stale.length === 0
        ? "route types: current"
        : `route types: STALE (${stale.map(([rel]) => rel).join(", ")}) — run node tooling/scripts/gen-route-types.mjs`,
    );
    process.exit(stale.length === 0 ? 0 : 1);
  }
  for (const [rel, want] of outs) {
    const file = path.join(root, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, want);
    console.log(`wrote ${rel}`);
  }
}
