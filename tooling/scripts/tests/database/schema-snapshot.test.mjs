/**
 * What the schema snapshot keeps of a pg_dump, and how it reads SQL, run over dumps and migrations in miniature.
 *
 * The snapshot must be the same bytes from any replay of the same migrations: a replay in October has partitions of
 * `events` one in August does not, pg_dump writes a new `\restrict` key every run, and a Windows checkout replays
 * bodies with CR LF. None of that is schema. Everything else is, byte for byte, because the rule test holds each
 * function's body there to its newest migration. schema-snapshot.db.test.mjs runs the script against the stack.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { containerOf, functionChangesIn, normalise } from "../../gen/schema-snapshot.mjs";

/** A pg_dump of `public` in miniature, in the order and shape pg_dump writes one. */
function dump({ months = ["2026m09", "2026m10"], key = "Abc123" } = {}) {
  const entry = (name, type, sql) => [
    `--`,
    `-- Name: ${name}; Type: ${type}; Schema: public; Owner: -`,
    `--`,
    ``,
    sql,
    ``,
    ``,
  ];
  return [
    "--",
    "-- PostgreSQL database dump",
    "--",
    "",
    `\\restrict ${key}`,
    "",
    "-- Dumped from database version 17.6",
    "-- Dumped by pg_dump version 17.6",
    "",
    "SET statement_timeout = 0;",
    "SELECT pg_catalog.set_config('search_path', '', false);",
    "",
    ...entry(
      "touch(uuid)",
      "FUNCTION",
      "CREATE FUNCTION public.touch(p_id uuid) RETURNS void\n    LANGUAGE sql\n    AS $$\n  select 1;\n\n\n  select 2;\n$$;",
    ),
    ...entry(
      "events",
      "TABLE",
      "CREATE TABLE public.events (\n    id uuid NOT NULL\n)\nPARTITION BY RANGE (created_at);",
    ),
    ...entry("events_default", "TABLE", "CREATE TABLE public.events_default (\n    id uuid NOT NULL\n);"),
    ...months.flatMap((m) => [
      ...entry(`events_y${m}`, "TABLE", `CREATE TABLE public.events_y${m} (\n    id uuid NOT NULL\n);`),
      ...entry(
        `events_y${m}_pkey`,
        "INDEX ATTACH",
        `ALTER INDEX public.events_pkey ATTACH PARTITION public.events_y${m}_pkey;`,
      ),
      ...entry(`TABLE events_y${m}`, "ACL", `GRANT ALL ON TABLE public.events_y${m} TO service_role;`),
    ]),
    ...entry(
      "DEFAULT PRIVILEGES FOR TABLES",
      "DEFAULT ACL",
      "ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT ALL ON TABLES TO service_role;",
    ),
    ...entry(
      "DEFAULT PRIVILEGES FOR TABLES",
      "DEFAULT ACL",
      "ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin IN SCHEMA public GRANT ALL ON TABLES TO anon;",
    ),
    "--",
    "-- PostgreSQL database dump complete",
    "--",
    "",
    `\\unrestrict ${key}`,
    "",
  ].join("\n");
}

test("two replays a month apart, on two machines, snapshot the same bytes", () => {
  const august = normalise(dump({ months: ["2026m08", "2026m09"], key: "one" }));
  const october = normalise(dump({ months: ["2026m10", "2026m11", "2026m12"], key: "two" }).replace(/\n/g, "\r\n"));
  assert.equal(october, august);
});

test("the snapshot keeps the schema and leaves out the run, the calendar and the platform", () => {
  const s = normalise(dump());
  assert.match(s, /^--\n-- GENERATED by tooling\/scripts\/gen\/schema-snapshot\.mjs/);
  assert.doesNotMatch(s, /\\(un)?restrict|Dumped (from|by)|dump complete/, "the run's own lines");
  assert.doesNotMatch(s, /events_y\d{4}m\d{2}/, "a month's partition, its index and its grant");
  assert.doesNotMatch(s, /supabase_admin/, "the platform role's default privileges");
  assert.match(s, /CREATE TABLE public\.events_default/, "the default partition is the schema's");
  assert.match(s, /FOR ROLE postgres IN SCHEMA public GRANT ALL ON TABLES TO service_role/, "a migration's default");
  assert.ok(
    s.includes("AS $$\n  select 1;\n\n\n  select 2;\n$$;"),
    "a body is kept byte for byte, blank lines and all",
  );
  assert.ok(s.endsWith(";\n") && !s.includes("\r"), "LF, ending on the last entry");
});

test("a dump that is not one is refused, not snapshotted as empty", () => {
  assert.throws(() => normalise("pg_dump: error: connection refused\n"), /not a pg_dump/);
});

test("the stack's container is named as the CLI names it", () => {
  assert.equal(
    containerOf('project_id = "chanlytics-messaging"\n[api]\nport = 54321\n'),
    "supabase_db_chanlytics-messaging",
  );
  assert.equal(containerOf('# a comment\nproject_id = "my project!"\n'), "supabase_db_my_project_");
  assert.equal(containerOf("[api]\nport = 54321\n"), null);
});

test("a function is known by its name and the types it takes in, spelled the way the dump spells them", () => {
  const migration = `
    -- a comment with a ; in it
    create or replace function public.people_list(p_tenant uuid, p_limit int default 50, p_since timestamptz = now(),
      out total bigint, p_tags text[] default '{}') returns setof record language plpgsql as $fn$
    begin
      perform 'a;b', E'it\\'s';
      return;
    end;
    $fn$;
    drop function if exists public.people_list(uuid, integer), public.gone(double precision);
    drop function public.whole;
    create trigger t after insert on public.x for each row execute function public.touch();
  `;
  const dumped = `CREATE FUNCTION public.people_list(p_tenant uuid, p_limit integer DEFAULT 50, p_since timestamp with time zone DEFAULT now(), OUT total bigint, p_tags text[] DEFAULT '{}'::text[]) RETURNS SETOF record
    LANGUAGE plpgsql
    AS $_$
    begin
      perform 'a;b', E'it\\'s';
      return;
    end;
    $_$;`;
  const [created, ...dropped] = functionChangesIn(migration);
  assert.deepEqual(
    { kind: created.kind, identity: created.identity },
    { kind: "create", identity: "people_list(uuid, integer, timestamp with time zone, text[])" },
  );
  assert.equal(functionChangesIn(dumped)[0].identity, created.identity, "the migration's spelling and the dump's");
  assert.equal(functionChangesIn(dumped)[0].body, created.body, "the body inside its tag, whatever the tag");
  assert.match(created.body, /perform 'a;b'/, "a ; inside the body does not end the statement");
  assert.deepEqual(
    dropped.map((d) => `${d.kind} ${d.identity}`),
    ["drop people_list(uuid, integer)", "drop gone(double precision)", "drop whole(*)"],
  );
});
