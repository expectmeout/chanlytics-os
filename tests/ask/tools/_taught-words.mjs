/** A frozen value (a tool, an answer, a string) read in today's words: every string in it, each pair in turn. */
export const taughtToday = (value) =>
  typeof value === "string"
    ? TAUGHT_WORDS.reduce((said, [was, is]) => said.replaceAll(was, is), value)
    : Array.isArray(value)
      ? value.map(taughtToday)
      : value && typeof value === "object"
        ? Object.fromEntries(Object.entries(value).map(([key, inner]) => [key, taughtToday(inner)]))
        : value;
